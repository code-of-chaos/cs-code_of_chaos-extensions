using Microsoft.Extensions.ObjectPool;

namespace CodeOfChaos.Extensions.ObjectPool;
// ---------------------------------------------------------------------------------------------------------------------
// Code
// ---------------------------------------------------------------------------------------------------------------------
public class QueuePoolPolicy<T, TItem> : IPooledObjectPolicy<T> 
    where T : Queue<TItem>, new()
{
    public T Create() => new();
    public bool Return(T obj) {
        obj.Clear();
        return obj.Count == 0;
    }
}
