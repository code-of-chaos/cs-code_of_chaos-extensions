using Microsoft.Extensions.ObjectPool;

namespace CodeOfChaos.Extensions.ObjectPool;
// ---------------------------------------------------------------------------------------------------------------------
// Code
// ---------------------------------------------------------------------------------------------------------------------
public class ResettablePoolPolicy<T> : IPooledObjectPolicy<T> where T : IResettable, new() {
    public T Create() => new();
    public bool Return(T obj) => obj.TryReset();
}
